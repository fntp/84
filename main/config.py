# -*- coding: utf-8 -*-
"""全项目的路径和默认值，只此一份，别处不允许再硬编码。

为什么要单独一个文件？
    模型文件在哪、输出目录在哪、默认阈值是多少 —— 这些东西散落在
    各个脚本里时，改一个位置就要翻遍全项目。集中在这里，
    只改一处，全项目生效。

路径怎么算的？
    config.py 位于 <项目根>/main/config.py
    dirname 一次 -> <项目根>/main
    dirname 两次 -> <项目根>
    所以 ROOT 永远等于项目根目录，不管从哪个盘符、哪个当前目录启动。
"""

import os

# ----------------------------------------------------------------------
# 一、路径
# ----------------------------------------------------------------------

# 项目根目录（weights/、out/、docs/ 都挂在这个下面）
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# 模型权重目录
WEIGHTS_DIR = os.path.join(ROOT, 'weights')

# 运行输出目录（日志、jsonl 都写这里）
OUT_DIR = os.path.join(ROOT, 'out')

# ----------------------------------------------------------------------
# 二、默认使用的模型
# ----------------------------------------------------------------------

# 默认 engine：fp16 量化版，90 MB，实测 2.58 ms / 387 FPS
DEFAULT_ENGINE = os.path.join(WEIGHTS_DIR, 'best_fp16.engine')

# fp32 版本，精度基准，用来跟 fp16 对比误差（109.7 MB，慢一些）
FP32_ENGINE = os.path.join(WEIGHTS_DIR, 'best_fp32.engine')

# 默认记录文件（只有加 --record 才会写）
DEFAULT_LOG = os.path.join(OUT_DIR, 'live_detect_log.txt')
DEFAULT_JSONL = os.path.join(OUT_DIR, 'detection_output.jsonl')

# ----------------------------------------------------------------------
# 三、模型输入规格（要跟导出 engine 时保持一致，改不了）
# ----------------------------------------------------------------------

# 网络输入边长：YOLOv5 固定 640x640
INPUT_SIZE = 640

# ----------------------------------------------------------------------
# 四、推理默认参数
# ----------------------------------------------------------------------

# 置信度阈值：低于这个分数的框直接丢掉。调高 -> 漏检变多、误检变少
DEFAULT_CONF = 0.25

# NMS 的 IoU 阈值：两个框重叠超过这个比例就认为是同一个目标，只留分高的那个
DEFAULT_IOU = 0.45

# ----------------------------------------------------------------------
# 五、抓屏默认参数
# ----------------------------------------------------------------------

# 默认抓几帧。0 表示【一直监听】直到 Ctrl+C 或 --stop，这是默认行为；
# 填 N 就抓 N 帧然后退出。1 也是"只跑一帧"，和 0 不是一回事。
DEFAULT_LOOP = 0

# 帧与帧之间至少隔多少秒（下限，不是等待时间）。
# 抓屏 + 推理本身就要几十毫秒，所以这里减去已经花掉的时间，
# 只补剩下的：设 0.02 时实际帧间隔就是 max(0.02, 抓屏+推理耗时)。
# 值定得比耗时小 = 全速跑，一帧接一帧，这是跟随该有的样子；
# 原来写 0.1 是【抓完再额外等 0.1 秒】，等于把帧率砍到 7 左右，
# 准星就一格一格慢慢滑过去，用户要的是开镜就贴上。
DEFAULT_INTERVAL = 0.02

# 每处理多少帧清理一次缓存（gc + 裁 jsonl）。0 表示不清理
CLEANUP_EVERY = 100

# jsonl 文件最多保留多少行，超出的从最老的开始丢
KEEP_LINES = 100

# ----------------------------------------------------------------------
# 六、后台模式用到的文件
# ----------------------------------------------------------------------

# 后台进程的 pid。--status / --stop 靠它找到那个进程
BG_PID = os.path.join(OUT_DIR, 'bg.pid')

# 后台进程的输出（相当于它的控制台，出错也记在这里）
BG_LOG = os.path.join(OUT_DIR, 'bg.log')

# 后台进程的坐标流：一行一帧，每行一个 JSON 数组
BG_COORDS = os.path.join(OUT_DIR, 'coords.jsonl')

# ----------------------------------------------------------------------
# 七、跟随瞄准（右键开关 + 相对移动）
# ----------------------------------------------------------------------

# 跟随开关用的虚拟键码。0x02 = VK_RBUTTON（鼠标右键），0x01 是左键，0x04 中键。
# 按着这个键就跟随，松开就停手。
# 想换成别的键（比如侧键、键盘键）改这里就行，键码表搜 "Virtual-Key Codes"。
TRIGGER_VK = 0x02

# 没按右键的时候，主循环空转的间隔，单位秒。
# 这段时间不抓屏、不推理、不移动，只是隔一会儿问一句"按上了没有"。
#
# 这个数就是【按下右键】到【第一帧开始抓屏】之间那段死等：键是 trigger 那个
# 读键线程在读（它自己 5 毫秒读一次），主循环要等到下一次空转才看得见。
# 所以取成跟读键线程同一个节奏 —— 用户要的是"开镜就贴上"，
# 不该在真正开始瞄之前先白等半帧。
#
# 不用心疼这点空转：跟一帧的耗时（抓屏 + 推理，几十毫秒）比可以忽略，
# 关着的时候每 5 毫秒醒一次也只是做一次比较。
IDLE_INTERVAL = 0.005

# 跟随的最低置信度。比检测阈值 DEFAULT_CONF 高得多，因为检测漏一个无所谓，
# 瞄错一个（打到队友/平民）才是事故。0.6 沿用以前那套的默认值，手感上没出过问题。
FOLLOW_MIN_CONFIDENCE = 0.6

# 增益：屏幕像素差 -> 鼠标计数。这只是【第一帧的起点】——
# 从第二帧起由 aim.GainTuner 按实测结果自己改，因为"推几个计数镜头转几像素"
# 取决于游戏灵敏度，同一台机器换个游戏、改个设置就变，猜不出一个通用值。
# 所以这个数不需要调：填个大概就行，标定几帧内会把它纠到该在的地方。
AIM_GAIN = 0.5

# 死区半径，单位像素。目标离准星这么近就不再动鼠标了 ——
# 框中心本来就会跳，不留死区的话准星会跟着一起抖。
AIM_DEADZONE = 12
