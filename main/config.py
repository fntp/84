# -*- coding: utf-8 -*-
"""全项目的路径和默认值，只此一份，别处不允许再硬编码。

为什么要单独一个文件？
    模型文件在哪、输出目录在哪、默认阈值是多少 —— 这些东西散落在
    各个脚本里时，改一个位置就要翻遍全项目。集中在这里，
    只改一处，全项目生效。

路径怎么算的？
    config.py 位于 <项目根>/main/config.py
    dirname 一次 -> <项目根>/main
    dirname 两次 -> <项目根>
    所以 ROOT 永远等于项目根目录，不管从哪个盘符、哪个当前目录启动。
"""

import os

# ----------------------------------------------------------------------
# 一、路径
# ----------------------------------------------------------------------

# 项目根目录（weights/、out/、docs/ 都挂在这个下面）
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# 模型权重目录
WEIGHTS_DIR = os.path.join(ROOT, 'weights')

# 运行输出目录（日志、jsonl 都写这里）
OUT_DIR = os.path.join(ROOT, 'out')

# ----------------------------------------------------------------------
# 二、默认使用的模型
# ----------------------------------------------------------------------

# 默认 engine：fp16 量化版，90 MB，实测 2.58 ms / 387 FPS
DEFAULT_ENGINE = os.path.join(WEIGHTS_DIR, 'best_fp16.engine')

# fp32 版本，精度基准，用来跟 fp16 对比误差（109.7 MB，慢一些）
FP32_ENGINE = os.path.join(WEIGHTS_DIR, 'best_fp32.engine')

# 默认记录文件（只有加 --record 才会写）
DEFAULT_LOG = os.path.join(OUT_DIR, 'live_detect_log.txt')
DEFAULT_JSONL = os.path.join(OUT_DIR, 'detection_output.jsonl')

# ----------------------------------------------------------------------
# 三、模型输入规格（要跟导出 engine 时保持一致，改不了）
# ----------------------------------------------------------------------

# 网络输入边长：YOLOv5 固定 640x640
INPUT_SIZE = 640

# ----------------------------------------------------------------------
# 四、推理默认参数
# ----------------------------------------------------------------------

# 置信度阈值：低于这个分数的框直接丢掉。调高 -> 漏检变多、误检变少
DEFAULT_CONF = 0.25

# NMS 的 IoU 阈值：两个框重叠超过这个比例就认为是同一个目标，只留分高的那个
DEFAULT_IOU = 0.45

# ----------------------------------------------------------------------
# 五、抓屏默认参数
# ----------------------------------------------------------------------

# 默认抓几帧。0 表示【一直监听】直到 Ctrl+C 或 --stop，这是默认行为；
# 填 N 就抓 N 帧然后退出。1 也是"只跑一帧"，和 0 不是一回事。
DEFAULT_LOOP = 0

# 多帧之间的间隔，单位秒。0.1 = 每秒大约 10 次
DEFAULT_INTERVAL = 0.1

# 每处理多少帧清理一次缓存（gc + 裁 jsonl）。0 表示不清理
CLEANUP_EVERY = 100

# jsonl 文件最多保留多少行，超出的从最老的开始丢
KEEP_LINES = 100

# ----------------------------------------------------------------------
# 六、后台模式用到的文件
# ----------------------------------------------------------------------

# 后台进程的 pid。--status / --stop 靠它找到那个进程
BG_PID = os.path.join(OUT_DIR, 'bg.pid')

# 后台进程的输出（相当于它的控制台，出错也记在这里）
BG_LOG = os.path.join(OUT_DIR, 'bg.log')

# 后台进程的坐标流：一行一帧，每行一个 JSON 数组
BG_COORDS = os.path.join(OUT_DIR, 'coords.jsonl')
